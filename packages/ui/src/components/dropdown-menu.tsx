/** A submenu: its trigger is an item with a caret, its content opens beside it. */
function DropdownMenuSub({ ...props }: MenuPrimitive.SubmenuRoot.Props) {
  return <MenuPrimitive.SubmenuRoot data-slot="dropdown-menu-sub" {...props} />
}

function DropdownMenuSubTrigger({ className, children, ...props }: MenuPrimitive.SubmenuTrigger.Props) {
  return (
    <MenuPrimitive.SubmenuTrigger
      data-slot="dropdown-menu-sub-trigger"
      className={cn(ITEM, "data-popup-open:bg-accent data-popup-open:text-accent-foreground", className)}
      {...props}
    >
      {children}
      <CaretRightIcon className="ml-auto" />
    </MenuPrimitive.SubmenuTrigger>
  )
}

function DropdownMenuSubContent({ side = "right", align = "start", alignOffset = -4, sideOffset = 2, ...props }: React.ComponentProps<typeof DropdownMenuContent>) {
  return <DropdownMenuContent side={side} align={align} alignOffset={alignOffset} sideOffset={sideOffset} {...props} />
}

